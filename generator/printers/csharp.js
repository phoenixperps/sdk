const HEAD = '// <auto-generated>\n// Generated from the API spec by generator/printers/csharp.js. Do not edit: run `node generator`.\n// </auto-generated>\n';
// (any other character, as in the value 24/7, becomes _ inside its word: V24_7)
const pascal = (s) => String(s).split(/[_\s.-]+/).filter(Boolean).map((w) => w.replace(/[^A-Za-z0-9]+/g, '_')).map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join('').replace(/^(\d)/, 'V$1');
const camel = (s) => {
  const p = pascal(s);
  const c = p.charAt(0).toLowerCase() + p.slice(1);
  return ['event', 'object', 'params', 'string', 'base', 'operator', 'checked', 'lock', 'out', 'ref', 'in', 'is', 'as'].includes(c) ? `@${c}` : c;
};
const methodPascal = (m) => m.charAt(0).toUpperCase() + m.slice(1);
const RESOURCE_NAMES = { tradingview: 'TradingView' };
const resName = (r) => RESOURCE_NAMES[r] || methodPascal(r);
const xml = (s) => String(s || '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\s+/g, ' ').trim();
const summary = (text, indent) => (text ? `${indent}/// <summary>${xml(text)}</summary>\n` : '');
const str = (s) => JSON.stringify(s);

const VALUE_TYPES = new Set(['int', 'bool', 'number', 'decimal', 'decimalIn', 'enum']);
function csType(t, optional) {
  const nullable = t.nullable || optional;
  let base;
  switch (t.kind) {
    case 'string': return nullable ? 'string?' : 'string';
    case 'int': base = 'long'; break;
    case 'bool': base = 'bool'; break;
    case 'number': base = 'double'; break;
    case 'decimal': case 'decimalIn': base = 'decimal'; break;
    case 'enum': base = t.name; break;
    case 'ref': return nullable ? `${t.name}?` : t.name;
    case 'array': return `List<${csType(t.of, false)}>${nullable ? '?' : ''}`;
    case 'map': return `Dictionary<string, JsonElement>${nullable ? '?' : ''}`;
    default: return 'JsonElement?';
  }
  return VALUE_TYPES.has(t.kind) && nullable ? `${base}?` : base;
}
const initFor = (t, optional) => {
  if (t.nullable || optional) return '';
  if (t.kind === 'string') return ' = "";';
  if (t.kind === 'array' || t.kind === 'map') return ' = new();';
  if (t.kind === 'ref') return ' = null!;';
  return '';
};

function propName(cls, wire) {
  const p = pascal(wire);
  // a member cannot share its class's name: Limit.limit is Limit.Value
  if (p === cls) return 'Value';
  if (p === 'Extra') return 'ExtraField';
  return p;
}

